// 공공데이터에 섞여 들어온 개인정보 가리기.
// 스포츠강좌이용권 강좌 이름에는 시설이 수강생 한 명을 위해 만든 '개인 결제창'이 있어,
// '이*람(핸드폰뒤7909) 소수수영 개인결제창'처럼 가린 이름·전화 뒷자리가 들어 있다 (대부분 어린이).
// 이런 강좌는 원자료를 받을 때부터 버리고, 남은 글자에서도 전화번호·이메일을 지운다.

/** 가린 이름(이*람·최ㅇ준·신○찬·[**은]·김시*)이나 개인 결제창 표시가 있는 강좌 이름 */
export const PERSONAL_SLOT_RE = new RegExp(
  [
    // 이*람, 최ㅇ준, 신○찬 (요일 '화*목'은 아님)
    '(?<![가-힣])(?![월화수목금토일][*＊ㅇ○][월화수목금토일])[가-힣][*＊ㅇ○][가-힣](?=$|[^가-힣]|회원|님|태권|수영)',
    // 김시*, 배수＊ (뒤에 괄호·숫자·밑줄)
    '(?<![가-힣])[가-힣]{2}[*＊](?=\\s*[()\\[\\]\\d_])',
    // 김○_, 김* 7월 (한 글자 성 + 가림표)
    '(?<![가-힣\\d])[가-힣][*＊○](?=[_)\\]]|\\s+\\d|$)',
    // [**은], [**현, **호]
    '\\[\\*\\*[가-힣]{1,2}',
    // 박시안회원_16B1
    '(?<![가-힣])[가-힣]{2,3}\\s?회원\\s*_',
    '핸드폰',
    '개인\\s*결[제체]\\s*창',
    '개인\\s*창',
    '개인결제\\s*\\(',
  ].join('|'),
);

export function isPersonalSlot(courseName: string): boolean {
  return PERSONAL_SLOT_RE.test(courseName);
}

/** 전화번호(구분자가 띄어 쓰였거나 점이어도)·이메일을 지운다 */
export function scrubContacts(text: string): string {
  return text
    .replace(/0\d{1,2}\D{0,4}\d{3,4}\D{0,4}\d{4}/g, '')
    .replace(/[\w.+-]+@[\w-]+\.[\w.-]+/g, '')
    .replace(/\s{2,}/g, ' ')
    .trim();
}
